export const GLYPH_H = 5;
export const LINE_H = 7;

function glyph(ch: string): readonly string[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS["?"]!;
}

export function pixelTextSupports(text: string): boolean {
  return [...text].every((ch) => GLYPHS[ch.toUpperCase()] !== undefined);
}

export function measureText(text: string, scale = 1): number {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0]!.length + 1;
  return Math.max(0, w - 1) * scale;
}

/** Pixel rects (x, y, w, h) for the text, merging horizontal runs. */
export function textRects(text: string, scale = 1): [number, number, number, number][] {
  const rects: [number, number, number, number][] = [];
  let cx = 0;
  for (const ch of text) {
    const g = glyph(ch);
    for (let row = 0; row < GLYPH_H; row++) {
      const line = g[row]!;
      let run = -1;
      for (let col = 0; col <= line.length; col++) {
        const on = line[col] === "#";
        if (on && run < 0) run = col;
        if (!on && run >= 0) {
          rects.push([(cx + run) * scale, row * scale, (col - run) * scale, scale]);
          run = -1;
        }
      }
    }
    cx += g[0]!.length + 1;
  }
  return rects;
}

export function truncate(text: string, maxWidth: number, scale = 1): string {
  if (measureText(text, scale) <= maxWidth) return text;
  let out = text;
  while (out.length > 0 && measureText(`${out}…`, scale) > maxWidth) out = out.slice(0, -1);
  return `${out.trimEnd()}…`;
}
